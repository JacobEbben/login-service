/** @type {'en'|'nl'} */
let current = 'nl';

/** @param {string} value */
export function setLang(value) { current = value === 'en' ? 'en' : 'nl'; }
export function lang() { return current; }

/** The text for ``key`` ('' when unknown). @param {string} key @param {...any} args */
export function t(key, ...args) {
  const v = TEXTS[current][key] ?? TEXTS.en[key];
  if (v === undefined) return '';
  return typeof v === 'function' ? v(...args) : v;
}
